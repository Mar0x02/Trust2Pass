def detect_language() -> str:
    code = QLocale.system().name().split("_")[0].lower()
    return code if code in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


_current_language = detect_language()


def get_language() -> str:
    return _current_language


def set_language(code: str) -> None:
    """Override manual (dipakai self-check biar hasilnya deterministik, gak ikut locale mesin
    yang jalanin test)."""
    global _current_language
    _current_language = code if code in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def tr(key: str, **kwargs) -> str:
    template = STRINGS.get(_current_language, {}).get(key)
    if template is None:
        template = STRINGS[DEFAULT_LANGUAGE].get(key, key)
    return template.format(**kwargs) if kwargs else template


